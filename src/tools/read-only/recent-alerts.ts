import { Type } from "typebox";
import type { Clock } from "../../shared/types.js";
import type { AlertRecord, WayfinderDatabase } from "../../storage/database.js";
import { EmptyToolParameters, envelopeSchema, type ToolDefinition } from "../contracts.js";

export interface RecentAlertsData {
  alerts: AlertRecord[];
}

const dataSchema = Type.Object(
  {
    alerts: Type.Array(
      Type.Object(
        {
          id: Type.String({ maxLength: 128 }),
          severity: Type.Union([Type.Literal("info"), Type.Literal("warning"), Type.Literal("critical")]),
          status: Type.Union([
            Type.Literal("firing"),
            Type.Literal("resolved"),
            Type.Literal("acknowledged"),
          ]),
          title: Type.String({ maxLength: 160 }),
          summary: Type.String({ maxLength: 500 }),
          createdAt: Type.String({ format: "date-time" }),
          updatedAt: Type.String({ format: "date-time" }),
          resolvedAt: Type.Optional(Type.String({ format: "date-time" })),
        },
        { additionalProperties: false },
      ),
      { maxItems: 100 },
    ),
  },
  { additionalProperties: false },
);

export function createRecentAlertsTool(
  database: WayfinderDatabase,
  clock: Clock,
): ToolDefinition<RecentAlertsData> {
  return {
    name: "get_recent_alerts",
    label: "Recent alerts",
    description: "Read recent alerts generated by Wayfinder. This does not run new system probes.",
    risk: "read_only",
    executionMode: "parallel",
    parameters: EmptyToolParameters,
    outputSchema: envelopeSchema(dataSchema),
    execute: async () => {
      const started = performance.now();
      return {
        schemaVersion: 1,
        status: "ok",
        observedAt: clock.now().toISOString(),
        durationMs: Math.max(0, Math.round(performance.now() - started)),
        data: { alerts: database.getRecentAlerts(20) },
        warnings: [],
      };
    },
  };
}
